"""
Chaos Chess - Game Engine Controller
"""
import time
import json
from typing import Optional, List, Tuple, Dict, Any
from config import (
    TEAM_RED, TEAM_BLUE, DEFAULT_TURN_LIMIT, SETTINGS_FILE, MATCH_HISTORY_FILE
)
from game.board import Board
from game.game_state import GameState
from game.movement import Move


class GameEngine:
    """Coordinates match rules, player inputs, AI turns, and match recording."""

    def __init__(self, settings: Optional[Dict[str, Any]] = None):
        self.settings: Dict[str, Any] = settings or self._load_settings()
        self.csp_roster_summary: Dict[str, Dict[str, int]] = {}
        self.team_material_points: Dict[str, int] = {}
        
        # Initialize board: generate balanced army using CSP by default
        board = self._create_initial_board()
        self.state: GameState = GameState(board=board)
        self._record_roster_summary()
        
        self.history_states: List[GameState] = []
        self.is_paused: bool = False
        self.match_start_time: float = time.time()
        self.total_match_duration: float = 0.0
        self.last_ai_metrics: Dict[str, Any] = {}

    def _create_initial_board(self) -> Board:
        """Creates board using CSP with backtracking, or falls back to standard fixed setup."""
        use_csp = self.settings.get("use_csp_armies", True)
        if use_csp:
            try:
                from ai.csp import CSPTeamGenerator
                return CSPTeamGenerator().generate_balanced_board(symmetric=True)
            except Exception:
                b = Board()
                b.setup_standard_board()
                return b
        else:
            b = Board()
            b.setup_standard_board()
            return b

    def _record_roster_summary(self) -> None:
        """Summarizes piece composition and material points for both teams generated by CSP."""
        summary = {}
        points = {}
        for team in (TEAM_RED, TEAM_BLUE):
            counts: Dict[str, int] = {}
            total_pts = 0
            for p in self.state.board.get_team_pieces(team):
                counts[p.piece_type] = counts.get(p.piece_type, 0) + 1
                total_pts += p.value
            summary[team] = counts
            points[team] = total_pts
        self.csp_roster_summary = summary
        self.team_material_points = points

    def _load_settings(self) -> Dict[str, Any]:
        try:
            with open(SETTINGS_FILE, "r") as f:
                data = json.load(f)
                if "use_csp_armies" not in data:
                    data["use_csp_armies"] = True
                return data
        except Exception:
            return {
                "random_events_enabled": True,
                "event_frequency_turns": 8,
                "turn_limit": 100,
                "sound_enabled": True,
                "sound_volume": 0.7,
                "ai_move_delay_ms": 300,
                "difficulty": "Medium",
                "use_csp_armies": True
            }

    def start_new_match(
        self,
        custom_board: Optional[Board] = None,
        starting_team: str = TEAM_BLUE
    ) -> None:
        """Resets engine for a fresh game, generating a new CSP balanced army unless custom_board is specified."""
        board = custom_board if custom_board else self._create_initial_board()

        self.state = GameState(board=board)
        self.state.current_turn = starting_team
        self.state.battlefield_mgr.enabled = self.settings.get("random_events_enabled", True)
        self.state.battlefield_mgr.event_frequency = self.settings.get("event_frequency_turns", 8)
        self._record_roster_summary()
        self.history_states = []
        self.is_paused = False
        self.match_start_time = time.time()
        self.total_match_duration = 0.0
        self.last_ai_metrics = {}

    def execute_move(self, move: Move) -> bool:
        """Executes a move, saving previous state for undo capability."""
        if self.state.is_game_over:
            return False

        # Save snapshot for undo
        self.history_states.append(self.state.clone())

        # Apply move
        self.state.apply_move(move)

        if self.state.is_game_over:
            self.total_match_duration = time.time() - self.match_start_time
            self._save_match_record()

        return True

    def undo_last_move(self) -> bool:
        """Reverts the state to the previous turn."""
        if self.history_states:
            self.state = self.history_states.pop()
            return True
        return False

    def get_legal_moves(self) -> List[Move]:
        return self.state.get_all_legal_moves()

    def _save_match_record(self) -> None:
        """Records finished match data into match_history.json."""
        try:
            history = []
            try:
                with open(MATCH_HISTORY_FILE, "r") as f:
                    history = json.load(f)
            except Exception:
                history = []

            record = {
                "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
                "winner": self.state.winner,
                "victory_reason": self.state.victory_reason,
                "total_turns": self.state.turn_count,
                "total_moves": len(self.state.move_history),
                "duration_seconds": round(self.total_match_duration, 2),
                "red_captured_count": len(self.state.captured_pieces[TEAM_RED]),
                "blue_captured_count": len(self.state.captured_pieces[TEAM_BLUE])
            }
            history.append(record)
            with open(MATCH_HISTORY_FILE, "w") as f:
                json.dump(history, f, indent=2)
        except Exception:
            pass

